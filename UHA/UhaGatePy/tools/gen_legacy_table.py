#!/usr/bin/env python3
"""Generate uhagatepy/legacy_table.py from the UhaGate6 sources.

The old outputs (uha.json) must keep exactly the keys and the key order of UhaGate6, so the
table is generated from its sources and never edited by hand:

  UHA/UHA6/src/uha_vars.h        all "#define VAR_xxx <id>" lines   -> NAME_TO_ID
  UHA/UHA6/src/uha_json_body.inc the lines that build uha.json      -> UHA_JSON_ITEMS (in that order)

Run it again only if UhaGate6's variable list changes:  python tools/gen_legacy_table.py
"""
import re
import sys
from pathlib import Path

APP_DIR = Path(__file__).resolve().parent.parent
UHA6_SRC = APP_DIR.parent / "UHA6" / "src"
OUTPUT = APP_DIR / "uhagatepy" / "legacy_table.py"

# A normal line:   cJSON_AddItemToObject(Uha, "VAR_X", cJSON_CreateNumber(mVars[VAR_X]));
NORMAL = re.compile(r'^cJSON_AddItemToObject\(Uha, "(\w+)", cJSON_CreateNumber\(mVars\[(\w+)\]\)\);$')
# The one computed line (value = old variable * 10), see UHA5 CreateJson()
SCALED = re.compile(r'^cJSON_AddItemToObject\(Uha, "(\w+)", cJSON_CreateNumber\(\(mVars\[(\w+)\]\)\*(\d+)\)\);$')
UNIX_TIME = 'cJSON_AddItemToObject(Uha, "UnixTime", cJSON_CreateNumber(Time));'


def read_defines(path: Path) -> dict:
    ids = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"#define\s+(VAR_\w+)\s+(\d+)\s*$", line.strip())
        if m:
            ids[m.group(1)] = int(m.group(2))
    num = re.search(r"#define\s+NUM_OF_VARS\s+(\d+)", path.read_text(encoding="utf-8"))
    return ids, int(num.group(1))


def read_items(path: Path, ids: dict) -> list:
    text = path.read_text(encoding="utf-8")
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)           # block comments
    items = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        if line == UNIX_TIME:
            continue                                            # added by the writer, always last
        m = NORMAL.match(line)
        if m:
            key, var, factor = m.group(1), m.group(2), 1
        else:
            m = SCALED.match(line)
            if not m:
                sys.exit(f"unexpected line in {path.name}: {line}")
            key, var, factor = m.group(1), m.group(2), int(m.group(3))
        if var not in ids:
            sys.exit(f"{var} is not defined in uha_vars.h")
        items.append((key, var, factor))
    return items


def main() -> None:
    ids, num_of_vars = read_defines(UHA6_SRC / "uha_vars.h")
    items = read_items(UHA6_SRC / "uha_json_body.inc", ids)
    keys = [k for k, _, _ in items]
    if len(set(keys)) != len(keys):
        sys.exit("duplicate keys in uha.json body")

    out = ['"""Old (UhaGate5/6) variable table. GENERATED by tools/gen_legacy_table.py - do not edit.\n',
           'Source: UHA/UHA6/src/uha_vars.h and uha_json_body.inc.\n"""\n\n',
           f"NUM_OF_VARS = {num_of_vars}   # old variable ids are 0..NUM_OF_VARS-1\n\n",
           "# every old variable: define name -> id (same id space as VARS2)\nNAME_TO_ID = {\n"]
    out += [f'    "{name}": {i},\n' for name, i in ids.items()]
    out += ["}\n\n",
            "# uha.json in the original key order: (json key, variable name, factor).\n",
            "# value = old raw value * factor; the key UnixTime is appended after these.\nUHA_JSON_ITEMS = (\n"]
    out += [f'    ("{k}", "{v}", {f}),\n' for k, v, f in items]
    out += [")\n"]
    OUTPUT.write_text("".join(out), encoding="utf-8", newline="\n")
    print(f"{OUTPUT}: {len(ids)} variables, {len(items)} uha.json keys (+UnixTime)")


if __name__ == "__main__":
    main()
